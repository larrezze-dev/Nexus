import { Injectable, inject, signal } from '@angular/core';
import { Observable, from } from 'rxjs';
import { map } from 'rxjs/operators';
import { Api } from '../../../api/platform/api';
import { createLegalEntity } from '../../../api/platform/fn/legal-entities/create-legal-entity';
import { deactivateLegalEntity } from '../../../api/platform/fn/legal-entities/deactivate-legal-entity';
import { getLegalEntity } from '../../../api/platform/fn/legal-entities/get-legal-entity';
import { listLegalEntities } from '../../../api/platform/fn/legal-entities/list-legal-entities';
import { updateLegalEntity } from '../../../api/platform/fn/legal-entities/update-legal-entity';
import { CreateLegalEntityRequest } from '../../../api/platform/models/create-legal-entity-request';
import { LegalEntity } from '../../../api/platform/models/legal-entity';
import { LegalEntityListItem } from '../../../api/platform/models/legal-entity-list-item';
import { UpdateLegalEntityRequest } from '../../../api/platform/models/update-legal-entity-request';
import { NxSortModel, Page } from '../../../shared/ui/page.model';

/**
 * Facade for `LegalEntity` master data (`FE-R1`, `conventions-frontend.md
 * §2/§3`): the only thing between the `legal-entities/*` pages/components
 * and the `platform` API client generated by `ng-openapi-gen`. Exposes
 * `selected`/`loading`/`error` as signals and keeps the `ETag` of whatever
 * was last loaded or saved internally, so `update()`/`deactivate()` can send
 * `If-Match` (`conventions-api.md §5`) without the caller threading the
 * header through itself.
 *
 * `create()`/`update()`/`deactivate()` deliberately do NOT catch errors:
 * they let the raw `HttpErrorResponse` propagate to the calling detail page,
 * which reads `error.error.errors` (400 field errors) or passes
 * `error.error.code` to `NxI18nService.translateErrorCode()` (422).
 * `errorInterceptor` already handles 401/403/404/409-concurrency
 * navigation/dialogs itself.
 */
@Injectable({ providedIn: 'root' })
export class LegalEntitiesFacade {
  private readonly api = inject(Api);

  private readonly selectedSignal = signal<LegalEntity | null>(null);
  private readonly loadingSignal = signal(false);
  private readonly errorSignal = signal<string | null>(null);
  private etag: string | null = null;

  readonly selected = this.selectedSignal.asReadonly();
  readonly loading = this.loadingSignal.asReadonly();
  readonly error = this.errorSignal.asReadonly();

  /** `nx-data-grid`'s `fetch` callback. `page` is 0-based; the API's `page` query param is 1-based. */
  list(page: number, pageSize: number, sort: NxSortModel | null): Observable<Page<LegalEntityListItem>> {
    return from(
      this.api.invoke(listLegalEntities, {
        page: page + 1,
        pageSize,
        sort: sort ? `${sort.direction === 'desc' ? '-' : ''}${sort.colId}` : undefined,
      }),
    ).pipe(
      map((response) => ({
        items: response.items ?? [],
        page: (response.page ?? page + 1) - 1,
        pageSize: response.pageSize ?? pageSize,
        total: response.total ?? 0,
      })),
    );
  }

  /**
   * `nx-entity-picker`'s `search` callback, used when picking a
   * `BusinessUnit.legalEntityId`. `GET /v1/legal-entities` has no `q` query
   * parameter in the contract (only `page`/`pageSize`/`sort`), so this
   * fetches one page sorted by `code` and filters client-side on a
   * substring match of `code` — acceptable while the number of legal
   * entities per group stays small; revisit (back to Gate C) if that
   * stops being true.
   */
  search(query: string): Observable<LegalEntityListItem[]> {
    return from(this.api.invoke(listLegalEntities, { page: 1, pageSize: 100, sort: 'code' })).pipe(
      map((response) => {
        const needle = query.trim().toLowerCase();
        const items = response.items ?? [];
        return needle ? items.filter((item) => item.code.toLowerCase().includes(needle)) : items;
      }),
    );
  }

  async load(id: string): Promise<void> {
    this.loadingSignal.set(true);
    this.errorSignal.set(null);
    try {
      const response = await this.api.invoke$Response(getLegalEntity, { id });
      this.selectedSignal.set(response.body);
      this.etag = response.headers.get('ETag');
    } catch {
      this.selectedSignal.set(null);
      this.etag = null;
      this.errorSignal.set('load_failed');
    } finally {
      this.loadingSignal.set(false);
    }
  }

  async create(request: CreateLegalEntityRequest): Promise<LegalEntity> {
    const response = await this.api.invoke$Response(createLegalEntity, { body: request });
    this.selectedSignal.set(response.body);
    this.etag = response.headers.get('ETag');
    return response.body;
  }

  async update(id: string, request: UpdateLegalEntityRequest): Promise<LegalEntity> {
    const response = await this.api.invoke$Response(updateLegalEntity, {
      id,
      body: request,
      'If-Match': this.etag ?? undefined,
    });
    this.selectedSignal.set(response.body);
    this.etag = response.headers.get('ETag');
    return response.body;
  }

  async deactivate(id: string): Promise<LegalEntity> {
    const response = await this.api.invoke$Response(deactivateLegalEntity, {
      id,
      'If-Match': this.etag ?? undefined,
    });
    this.selectedSignal.set(response.body);
    this.etag = response.headers.get('ETag');
    return response.body;
  }

  /** Clears `selected`/`error`/the stored `ETag` — call when entering the detail page fresh. */
  reset(): void {
    this.selectedSignal.set(null);
    this.errorSignal.set(null);
    this.etag = null;
  }
}
